-- APP: schema della webapp di generazione immagini (generazioni, chat, catalogo modelli Replicate, LoRA, vector store). Si applica
-- dopo il core (versione a timestamp piu' recente). Storico: squash delle V1..V23 del periodo H2 e delle prime migrazioni Postgres
-- (le versioni originali restano nella storia git). Convenzioni e regola delle versioni: vedi db/migration/core.

CREATE EXTENSION IF NOT EXISTS vector;

CREATE TABLE chat_conversation (
    id         bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    title      varchar(255),
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT pk_chat_conversation PRIMARY KEY (id)
);

-- Una Generation avviata da /deep-chat ricorda la conversazione (NULL per il form diretto): serve a ripristinare il placeholder di
-- una generazione ancora in corso al reload. ON DELETE SET NULL: cancellare la conversazione non elimina le generazioni.
-- source_generation_id = generazione sorgente di un img2video ("Anima"), stesso ragionamento. cost_usd = costo stimato (snapshot,
-- NULL se non stimabile). source_upload_filename = immagine caricata per un img2video/edit stand-alone (non e' una Generation).
CREATE TABLE generation (
    id                     bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    external_id            varchar(255) NOT NULL,
    model                  varchar(255) NOT NULL,
    version                varchar(255),
    prompt                 text NOT NULL,
    parameters_json        text,
    seed                   bigint,
    status                 varchar(20) NOT NULL,
    kind                   varchar(10) NOT NULL DEFAULT 'IMAGE',
    error_message          text,
    cost_usd               numeric(12, 6),
    source_generation_id   bigint,
    source_upload_filename varchar(255),
    conversation_id        bigint,
    created_at             timestamptz NOT NULL,
    completed_at           timestamptz,
    CONSTRAINT pk_generation PRIMARY KEY (id),
    CONSTRAINT fk_generation_source FOREIGN KEY (source_generation_id) REFERENCES generation (id) ON DELETE SET NULL
);

-- File prodotti da una generazione (ordinati) e file con la star (preferiti, per singolo file).
CREATE TABLE generation_image (
    generation_id bigint NOT NULL,
    ordinal       int NOT NULL,
    filename      varchar(255) NOT NULL,
    CONSTRAINT pk_generation_image PRIMARY KEY (generation_id, ordinal),
    CONSTRAINT fk_generation_image_generation FOREIGN KEY (generation_id) REFERENCES generation (id)
);

CREATE TABLE generation_favourite (
    generation_id bigint NOT NULL,
    filename      varchar(255) NOT NULL,
    CONSTRAINT pk_generation_favourite PRIMARY KEY (generation_id, filename),
    CONSTRAINT fk_generation_favourite_generation FOREIGN KEY (generation_id) REFERENCES generation (id) ON DELETE CASCADE
);

-- generation_id ON DELETE SET NULL: il turno di chat resta (testo/ruolo), perde solo il riferimento all'immagine cancellata.
-- error = turno ASSISTANT di errore (escluso dal contesto inviato all'LLM).
CREATE TABLE chat_message (
    id              bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    conversation_id bigint NOT NULL,
    role            varchar(20) NOT NULL,
    content         text NOT NULL,
    generation_id   bigint,
    error           boolean NOT NULL DEFAULT FALSE,
    created_at      timestamptz NOT NULL,
    CONSTRAINT pk_chat_message PRIMARY KEY (id),
    CONSTRAINT fk_chat_message_conversation FOREIGN KEY (conversation_id) REFERENCES chat_conversation (id),
    CONSTRAINT fk_chat_message_generation FOREIGN KEY (generation_id) REFERENCES generation (id) ON DELETE SET NULL
);

-- Catalogo dei modelli Replicate proposti nelle form. form_type seleziona form/handler Java (GenerationFormType), varchar per non
-- richiedere una migrazione di tipo a ogni nuovo form-type (serve solo l'INSERT del seed).
CREATE TABLE replicate_model (
    id          bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    owner       varchar(255) NOT NULL,
    name        varchar(255) NOT NULL,
    version     varchar(255),
    description varchar(1024),
    form_type   varchar(30) NOT NULL,
    sort_order  int NOT NULL,
    active      boolean NOT NULL DEFAULT TRUE,
    created_at  timestamptz NOT NULL,
    CONSTRAINT pk_replicate_model PRIMARY KEY (id),
    CONSTRAINT uq_replicate_model_owner_name UNIQUE (owner, name)
);


-- Vector store della ricerca semantica (PgVectorStore di Spring AI, vedi CLAUDE.md "Ricerca semantica"): schema imposto dallo
-- store (id, content, metadata, embedding). id text perche' gli id sono "generation:12", "note:<uuid>". vector(384) = dimensione di
-- multilingual-e5-small: un modello con altre dimensioni richiede una nuova migrazione (ALTER ... TYPE vector(N), dopo aver
-- svuotato la tabella) e la reindicizzazione. NESSUN indice ANN (HNSW/IVFFlat): /search mostra TUTTA la classifica sopra soglia e un
-- indice approssimato tronca i risultati a ef_search (40); lo scan esatto a decine di migliaia di righe costa pochi ms.
-- L'hash del testo, il modello e la data di indicizzazione stanno nei metadata (chiavi riservate, vedi VectorIndexer).
CREATE TABLE vector_store (
    id        text PRIMARY KEY,
    content   text,
    metadata  json,
    embedding vector(384)
);

-- LoRA anagrafati (CRUD /loras, LoraPresetService): preset da scegliere nelle form di flux-dev-lora. Sono solo un aiuto di
-- compilazione (la form riceve comunque testo + scala): nessuna FK da generation.
CREATE TABLE lora_preset (
    id            bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name          varchar(60) NOT NULL,
    source        varchar(500) NOT NULL,
    scale         double precision NOT NULL DEFAULT 1,
    trigger_words varchar(500),
    note          varchar(500),
    created_at    timestamptz NOT NULL,
    updated_at    timestamptz NOT NULL,
    CONSTRAINT pk_lora_preset PRIMARY KEY (id),
    CONSTRAINT uq_lora_preset_name UNIQUE (name)
);

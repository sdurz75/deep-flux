-- Dataset di addestramento LoRA (feature training): bozza persistente di immagini + didascalie + configurazione.
-- `frozen` = snapshot di un training (sola lettura, fuori dall'elenco dei dataset): lo usera' la tabella dei training.
-- `source_dataset_id` e' la provenienza di un clone/snapshot e NON ha FK: la bozza di origine puo' sparire.

CREATE TABLE training_dataset (
    id                bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name              varchar(80) NOT NULL,
    trigger_word      varchar(40) NOT NULL,
    lora_type         varchar(20) NOT NULL,
    note              varchar(500),
    frozen            boolean NOT NULL DEFAULT false,
    source_dataset_id bigint,
    created_at        timestamptz NOT NULL,
    updated_at        timestamptz NOT NULL,
    -- Blocco ottimistico: il dataset si riscrive con le sue immagini (merge + orphanRemoval), e una richiesta con una copia vecchia
    -- cancellerebbe in silenzio le immagini aggiunte da un'altra. Con la versione fallisce invece di perderle.
    version           bigint NOT NULL DEFAULT 0,
    CONSTRAINT pk_training_dataset PRIMARY KEY (id)
);

CREATE INDEX idx_training_dataset_listing ON training_dataset (frozen, updated_at DESC);

-- Una riga possiede i suoi binari (nessuna dedup): `filename` e' l'immagine che andra' nello zip (ritagliata, oppure = originale),
-- `original_filename` l'originale caricato. `original_name` e' il nome del file sul disco dell'utente, solo da mostrare.
-- Crop (x, y, larghezza, altezza sull'originale, in pixel) e didascalia: usati dall'editor di ritaglio e dall'auto-caption.
-- caption_status DONE = nessun lavoro in corso (la didascalia puo' essere vuota).
CREATE TABLE training_image (
    id                bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    dataset_id        bigint NOT NULL,
    sort_order        integer NOT NULL,
    filename          varchar(255) NOT NULL,
    original_filename varchar(255) NOT NULL,
    original_name     varchar(255),
    crop_x            integer,
    crop_y            integer,
    crop_w            integer,
    crop_h            integer,
    caption           text,
    caption_source    varchar(10) NOT NULL DEFAULT 'NONE',
    caption_status    varchar(10) NOT NULL DEFAULT 'DONE',
    created_at        timestamptz NOT NULL,
    CONSTRAINT pk_training_image PRIMARY KEY (id),
    CONSTRAINT fk_training_image_dataset FOREIGN KEY (dataset_id) REFERENCES training_dataset (id) ON DELETE CASCADE
);

CREATE INDEX idx_training_image_dataset ON training_image (dataset_id, sort_order);
